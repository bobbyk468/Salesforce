#!/usr/bin/env node
/**
 * Moves each static `src/app/certifications/<slug>/page.tsx` into
 * `src/components/certifications/cert-bodies/<slug>.tsx`, strips generateMetadata,
 * regenerates `legacy-cert-slugs.generated.ts` and `load-legacy-cert-body.ts`.
 *
 * Run from repo root: node scripts/bulk-migrate-cert-legacy-bodies.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, unlinkSync, existsSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const CERT_APP = join(ROOT, 'src/app/certifications')
const OUT_DIR = join(ROOT, 'src/components/certifications/cert-bodies')
const SPIKE_DIR = join(ROOT, 'src/lib/cert-page-spike')

const SKIP_DIRS = new Set(['[slug]', 'role'])
const DATA_SLUGS = new Set(['ai-associate', 'app-builder', 'administrator', 'advanced-administrator'])

function stripGenerateMetadataBlock(src) {
  const marker = 'export async function generateMetadata'
  const i = src.indexOf(marker)
  if (i === -1) return src
  const braceOpen = src.indexOf('{', i)
  if (braceOpen === -1) return src
  let depth = 0
  let k = braceOpen
  for (; k < src.length; k++) {
    const ch = src[k]
    if (ch === '{') depth++
    else if (ch === '}') {
      depth--
      if (depth === 0) {
        k++
        break
      }
    }
  }
  while (k < src.length && (src[k] === ' ' || src[k] === '\t')) k++
  while (k < src.length && src[k] === '\n') k++
  return src.slice(0, i) + src.slice(k)
}

function stripMetadataImports(src) {
  let out = src
  out = out.replace(/import\s+type\s*\{\s*Metadata\s*\}\s*from\s*['"]next['"]\s*\n?/g, '')
  out = out.replace(/import\s*\{\s*Metadata\s*\}\s*from\s*['"]next['"]\s*\n?/g, '')
  return out
}

function stripGetCertMetadataFromSeoImport(src) {
  return src.replace(
    /import\s*\{([^}]*)\}\s*from\s*['"]@\/lib\/cert-seo-data['"]/g,
    (full, inner) => {
      const names = inner
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .filter((n) => n !== 'getCertMetadata')
      if (names.length === 0) return ''
      return `import { ${names.join(', ')} } from '@/lib/cert-seo-data'`
    },
  )
}

function dedupeBlankLines(src) {
  return src.replace(/\n{4,}/g, '\n\n\n')
}

mkdirSync(OUT_DIR, { recursive: true })

const entries = readdirSync(CERT_APP, { withFileTypes: true })
const slugs = []
for (const d of entries) {
  if (!d.isDirectory()) continue
  const name = d.name
  if (SKIP_DIRS.has(name)) continue
  if (DATA_SLUGS.has(name)) continue
  const pagePath = join(CERT_APP, name, 'page.tsx')
  if (!existsSync(pagePath)) continue
  slugs.push(name)
}
slugs.sort()

for (const slug of slugs) {
  const pagePath = join(CERT_APP, slug, 'page.tsx')
  let raw = readFileSync(pagePath, 'utf8')
  let transformed = stripGenerateMetadataBlock(raw)
  transformed = stripMetadataImports(transformed)
  transformed = stripGetCertMetadataFromSeoImport(transformed)
  transformed = dedupeBlankLines(transformed)

  const outPath = join(OUT_DIR, `${slug}.tsx`)
  writeFileSync(outPath, transformed, 'utf8')
  unlinkSync(pagePath)
  console.log('migrated', slug)
}

const slugListTs = slugs.map((s) => `  '${s}',`).join('\n')
const generatedSlugs = `/** Auto-generated by scripts/bulk-migrate-cert-legacy-bodies.mjs — do not edit by hand. */\nexport const LEGACY_CERT_SLUGS = [\n${slugListTs}\n] as const\n\nexport type LegacyCertSlug = (typeof LEGACY_CERT_SLUGS)[number]\n`
writeFileSync(join(SPIKE_DIR, 'legacy-cert-slugs.generated.ts'), generatedSlugs, 'utf8')

const cases = slugs
  .map(
    (s) => `    case '${s}':\n      return (await import('@/components/certifications/cert-bodies/${s}')).default`,
  )
  .join('\n')

const loader = `/** Auto-generated by scripts/bulk-migrate-cert-legacy-bodies.mjs — do not edit by hand. */
import type { ComponentType } from 'react'

export type LegacyCertPageBody = ComponentType

export async function loadLegacyCertBody(slug: string): Promise<LegacyCertPageBody | null> {
  switch (slug) {
${cases}
    default:
      return null
  }
}
`
writeFileSync(join(SPIKE_DIR, 'load-legacy-cert-body.ts'), loader, 'utf8')

console.log('\nDone. Legacy slugs:', slugs.length)
console.log('Wrote legacy-cert-slugs.generated.ts and load-legacy-cert-body.ts')
